void updateDisplay() {
  oled.clearDisplay();
  oled.setTextColor(SSD1306_WHITE);
  drawScreenIndicator();
  switch (currentScreen) {
    case 0: screenStatus();    break;
    case 1: screenSetpoints(); break;
    case 2: screenNetwork();   break;
    case 3: screenSnake();     break;
  }
  oled.display();
}
