static void drawScreenIndicator() {
  for (uint8_t i = 0; i < 4; i++) {
    uint8_t x = 118 + (i % 2) * 5;
    uint8_t y = (i / 2) * 5;
    if (i == currentScreen) oled.fillRect(x, y, 4, 4, SSD1306_WHITE);
    else                    oled.drawRect(x, y, 4, 4, SSD1306_WHITE);
  }
}

