bool initDisplay() {
  if (!oled.begin(SSD1306_SWITCHCAPVCC, 0x3C)) return false;
  oled.clearDisplay();
  oled.setTextColor(SSD1306_WHITE);
  oled.setTextSize(1);
  oled.setCursor(0, 0);  oled.println("Terrario BCC");
  oled.setCursor(0, 12); oled.println("Iniciando...");
  oled.display();
  return true;
}

